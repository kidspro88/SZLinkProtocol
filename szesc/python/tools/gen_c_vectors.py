#!/usr/bin/env python3
"""Write c/szfw_test_vectors.h: images signed by the Python implementation."""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "szlink", "python"))

import szfw  # noqa: E402
from szlink import crypto  # noqa: E402

SEED = bytes(range(0x20, 0x40))
OTHER_SEED = bytes(range(0xA0, 0xC0))
BODY = bytes((i * 37 + 11) & 0xFF for i in range(1000))


def c_bytes(name: str, data: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"static const uint8_t {name}[{len(data)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def main() -> None:
    out = ["/* Generated by szesc/python/tools/gen_c_vectors.py - do not edit. */",
           "#ifndef SZFW_TEST_VECTORS_H", "#define SZFW_TEST_VECTORS_H", "", "#include <stdint.h>", "",
           c_bytes("tv_key", crypto.identity_public(SEED)),
           c_bytes("tv_other_key", crypto.identity_public(OTHER_SEED)),
           c_bytes("tv_image", szfw.sign_image(SEED, BODY, board_id=7, fw_version=0x00010200, key_id=1)),
           "#endif", ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
