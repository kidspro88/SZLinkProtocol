#!/usr/bin/env python3
"""Generate szlink/c/szlink_test_vectors.h from the Python implementation.

The C tests replay these vectors to prove that szlink_sec.h / szlink_frame.h
are byte-for-byte compatible with the Python ground-station code.
tests/test_vectors.py fails if the checked-in header is stale.

    python3 szlink/python/tools/gen_c_vectors.py > szlink/c/szlink_test_vectors.h
"""

from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

from szlink import crypto  # noqa: E402
from szlink.frame import FrameCodec  # noqa: E402
from szlink.session import INITIATOR, RESPONDER, SEC_ENCRYPTED, SEC_SIGNED, SecureLink  # noqa: E402

GCS_PRIV = bytes(range(1, 33))
VEH_PRIV = bytes(range(101, 133))
GCS_EPH = bytes(range(201, 233))
VEH_EPH = bytes((i * 7 + 3) & 0xFF for i in range(32))
TIMESTAMP_US = 1_764_000_000_000_000
FEC_NSYM = 16
SHARED_SECRET = bytes(range(0x40, 0x60))

MSGS = {0: (50, 9), 54000: (58, 10), 54001: (141, 255)}

# (direction, msgid, lcid, mode, time_ms, sysid, compid, payload)
FRAMES = [
    ("g2v", 54000, 0, SEC_ENCRYPTED, 10, 255, 190, bytes([1, 1, 0x10, 0x27, 0, 0, 0xF0, 0xD8, 0x88, 0x13])),
    ("g2v", 0, 1, SEC_SIGNED, 40_000, 255, 190, bytes([0, 0, 0, 0, 6, 8, 0, 0, 3])),
    ("v2g", 0, 1, SEC_ENCRYPTED, 41_000, 1, 1, bytes([0, 0, 0, 0, 2, 3, 0x81, 0, 3])),
    ("v2g", 54001, 2, SEC_ENCRYPTED, 95_000, 1, 1, bytes((i * 13 + 5) & 0xFF or 1 for i in range(255))),
]


def build():
    gcs = SecureLink(INITIATOR, GCS_PRIV, crypto.x25519_public(VEH_PRIV))
    veh = SecureLink(RESPONDER, VEH_PRIV, crypto.x25519_public(GCS_PRIV))
    kex_init = gcs.kex_init(0, GCS_EPH, TIMESTAMP_US)
    kex_resp = veh.handle_kex_init(kex_init, 0, VEH_EPH)
    assert gcs.handle_kex_resp(kex_resp, 0)
    tx = {"g2v": FrameCodec(MSGS.get, gcs, FEC_NSYM), "v2g": FrameCodec(MSGS.get, veh, FEC_NSYM)}
    rx = {"g2v": FrameCodec(MSGS.get, veh, FEC_NSYM), "v2g": FrameCodec(MSGS.get, gcs, FEC_NSYM)}
    frames = []
    for direction, msgid, lcid, mode, t, sysid, compid, payload in FRAMES:
        wire = tx[direction].encode(msgid, payload, sysid, compid, lcid, mode=mode, now_ms=t)
        (got,) = rx[direction].parse(wire, t)
        assert got.payload == payload and got.authenticated
        frames.append((direction, msgid, lcid, mode, t, sysid, compid, payload, wire))
    return kex_init, kex_resp, frames


def c_bytes(name: str, data: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 12]) for i in range(0, len(data), 12)]
    body = ",\n    ".join(rows)
    return f"static const uint8_t {name}[{len(data)}] = {{\n    {body}\n}};\n"


def render() -> str:
    kex_init, kex_resp, frames = build()
    out = ["/* Generated by szlink/python/tools/gen_c_vectors.py - do not edit. */",
           "#ifndef SZLINK_TEST_VECTORS_H", "#define SZLINK_TEST_VECTORS_H", "",
           "#include <stdint.h>", "",
           f"#define TV_TIMESTAMP_US {TIMESTAMP_US}ULL",
           f"#define TV_FEC_NSYM {FEC_NSYM}u", "",
           c_bytes("tv_gcs_priv", GCS_PRIV), c_bytes("tv_veh_priv", VEH_PRIV),
           c_bytes("tv_gcs_eph", GCS_EPH), c_bytes("tv_veh_eph", VEH_EPH),
           c_bytes("tv_kex_init", kex_init), c_bytes("tv_kex_resp", kex_resp),
           c_bytes("tv_secret", SHARED_SECRET),
           c_bytes("tv_secret_vehicle_pub", crypto.x25519_public(crypto.keys_from_secret(SHARED_SECRET)[0])),
           c_bytes("tv_secret_ground_pub", crypto.x25519_public(crypto.keys_from_secret(SHARED_SECRET)[1]))]
    entries = []
    for i, (direction, msgid, lcid, mode, t, sysid, compid, payload, wire) in enumerate(frames):
        out.append(c_bytes(f"tv_frame{i}_payload", payload))
        out.append(c_bytes(f"tv_frame{i}_wire", wire))
        entries.append(f"    {{{int(direction == 'g2v')}, {msgid}u, {lcid}u, {mode}u, {t}u, "
                       f"{sysid}u, {compid}u, tv_frame{i}_payload, {len(payload)}u, "
                       f"tv_frame{i}_wire, {len(wire)}u}},")
    out += ["typedef struct {",
            "    uint8_t gcs_to_vehicle;",
            "    uint32_t msgid;",
            "    uint8_t lcid, mode;",
            "    uint32_t time_ms;",
            "    uint8_t sysid, compid;",
            "    const uint8_t *payload;",
            "    uint8_t payload_len;",
            "    const uint8_t *wire;",
            "    uint16_t wire_len;",
            "} tv_frame_t;", "",
            "static const tv_frame_t tv_frames[] = {", *entries, "};", "",
            "#endif", ""]
    return "\n".join(out)


if __name__ == "__main__":
    sys.stdout.write(render())
